"""
Embeds the compiled shaders in the binary: for each variant listed by
scripts/build_shaders.py, writes its SPIR-V as a uint32_t array plus one index
row per dtype it serves.

Output, in the build directory, included by the shader manager and the autotuner:

    shader_registry.h     declares SHADER_BINARIES and SHADER_INDEX
    shader_registry.cpp   defines them:

        static const uint32_t spv_binary_f32[] = { 0x07230203, ... };

        const ShaderBinary SHADER_BINARIES[] = {
            { "binary_f32", spv_binary_f32, sizeof(spv_binary_f32), 0x9f2c...ull },
        };

        const ShaderIndexEntry SHADER_INDEX[] = {
            { Kernel::BINARY, c10::ScalarType::Float, c10::ScalarType::Undefined, 0 },
        };

The arrays live in their own translation unit, so editing shader.cpp doesn't
recompile tens of megabytes of SPIR-V.
"""

import argparse
import hashlib
import itertools
import json
import struct
from pathlib import Path


def spv_to_c_array(spv_file: Path, array_name: str) -> tuple[str, int]:
    """Reads a .spv binary and formats it as a C++ uint32_t array definition, plus a 64-bit hash of its contents."""
    binary_data = spv_file.read_bytes()

    # pad to a multiple of 4 bytes
    if len(binary_data) % 4 != 0:
        binary_data += b'\x00' * (4 - (len(binary_data) % 4))

    words = struct.unpack(f'<{len(binary_data) // 4}I', binary_data)
    lines = []
    for i in range(0, len(words), 16):
        lines.append(','.join(f'0x{word:08x}' for word in words[i:i + 16]))
    body = ',\n'.join(lines)
    digest = int.from_bytes(hashlib.blake2b(binary_data, digest_size=8).digest(), 'little')
    return f'static const uint32_t {array_name}[] = {{\n{body}\n}};\n', digest


def index_rows(variant: dict, binary: int) -> list[str]:
    """
    One SHADER_INDEX row per aten dtype combination the variant serves - a u8
    variant serves both Byte and Bool, and a copy width serves every dtype of
    that size.
    """
    kernel = f'Kernel::{variant["kernel"].upper()}'
    rows = []

    for combo in itertools.product(*variant['aten']):
        dtype = f'c10::ScalarType::{combo[0]}'
        dtype2 = f'c10::ScalarType::{combo[1]}' if len(combo) > 1 else 'c10::ScalarType::Undefined'
        rows.append(f'    {{ {kernel}, {dtype}, {dtype2}, {binary} }}, // {variant["name"]}')

    return rows


def write_if_changed(path: Path, text: str):
    """Leaves the file untouched when nothing changed, so its dependents do not rebuild."""
    if path.exists() and path.read_text() == text:
        return
    path.write_text(text)


HEADER = '''// --- AUTO-GENERATED BY scripts/pack_shaders.py --- //
// Do not edit manually!

#pragma once
#include <c10/core/ScalarType.h>
#include <cstddef>
#include <cstdint>
#include "shader_kernels.h"

namespace torchvulkan {

struct ShaderBinary {
    const char* name;
    const uint32_t* code;
    size_t size;
    uint64_t hash;
};

struct ShaderIndexEntry {
    Kernel kernel;
    c10::ScalarType dtype;
    c10::ScalarType dtype2;
    uint32_t binary;
};

extern const ShaderBinary SHADER_BINARIES[];
extern const size_t NUM_SHADER_BINARIES;
extern const ShaderIndexEntry SHADER_INDEX[];
extern const size_t NUM_SHADER_INDEX;

} // namespace torchvulkan
'''


def main(args):
    variants = json.loads(args.variants.read_text())

    arrays = []
    binaries = []
    index = []

    for binary, variant in enumerate(variants):
        array_name = f'spv_{variant["name"]}'
        array, digest = spv_to_c_array(args.build / f'{variant["name"]}.spv', array_name)
        arrays.append(array)
        binaries.append(f'    {{ "{variant["name"]}", {array_name}, sizeof({array_name}), 0x{digest:016x}ull }},')
        index.extend(index_rows(variant, binary))

    source = [
        '// --- AUTO-GENERATED BY scripts/pack_shaders.py --- //',
        '// Do not edit manually!\n',
        f'#include "{args.header.name}"\n',
        'namespace torchvulkan {\n',
    ]
    source.extend(arrays)
    source.append('const ShaderBinary SHADER_BINARIES[] = {')
    source.extend(binaries)
    source.append('};\n')
    source.append('const size_t NUM_SHADER_BINARIES = sizeof(SHADER_BINARIES) / sizeof(SHADER_BINARIES[0]);\n')
    source.append('const ShaderIndexEntry SHADER_INDEX[] = {')
    source.extend(index)
    source.append('};\n')
    source.append('const size_t NUM_SHADER_INDEX = sizeof(SHADER_INDEX) / sizeof(SHADER_INDEX[0]);\n')
    source.append('} // namespace torchvulkan\n')

    args.out.parent.mkdir(parents=True, exist_ok=True)
    write_if_changed(args.header, HEADER)
    args.out.write_text('\n'.join(source))
    print(f'Packed {len(variants)} shaders into {args.out}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Pack compiled Vulkan shaders into a C++ source file.')
    parser.add_argument('--build', type=Path, default=Path('build/shaders'), help='Directory containing compiled .spv files')
    parser.add_argument('--variants', type=Path, default=Path('build/shaders/variants.json'), help='Variant list written by build_shaders.py')
    parser.add_argument('--out', type=Path, default=Path('build/generated/shader_registry.cpp'), help='Output source file path')
    parser.add_argument('--header', type=Path, default=Path('build/generated/shader_registry.h'), help='Output header file path')
    main(parser.parse_args())
